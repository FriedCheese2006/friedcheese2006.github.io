import unittest
from pathlib import Path
from tempfile import TemporaryDirectory

from scripts.check_requirements_lock import normalize_lock


class RequirementsLockTests(unittest.TestCase):
    def setUp(self):
        directory = TemporaryDirectory()
        self.addCleanup(directory.cleanup)
        self.lock = Path(directory.name) / "requirements.txt"

    def normalize(self, contents):
        self.lock.write_text(contents, encoding="utf-8")
        return normalize_lock(self.lock)

    def test_ignores_dependabot_annotations_and_extras(self):
        self.assertEqual(
            self.normalize(
                "uvicorn[standard]==0.54.0 \\\n"
                "    --hash=sha256:abc\n"
                "    # via -r requirements.in\n"
            ),
            self.normalize(
                "# Generated by pip-compile\n"
                "uvicorn==0.54.0 --hash=sha256:abc\n"
                "    # via -r backend/requirements.in\n"
            ),
        )

    def test_preserves_pins_hashes_markers_and_options(self):
        lock = "uvicorn==0.54.0 --hash=sha256:abc\n"
        for modified in (
            lock.replace("0.54.0", "0.55.0"),
            lock.replace("sha256:abc", "sha256:def"),
            lock.replace(" --hash=sha256:abc", ""),
            lock.replace(" --hash", ' ; python_version < "3.15" --hash'),
            "--index-url https://example.com/simple\n" + lock,
        ):
            with self.subTest(modified=modified):
                self.assertNotEqual(self.normalize(lock), self.normalize(modified))
